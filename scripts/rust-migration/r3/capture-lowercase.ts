/** Capture the retained Bun default Unicode lowercase kernel as inert Rust data. */
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const root=resolve(import.meta.dir,'../../..');
const out=resolve(root,'docs/helix/04-build/evidence/rust-migration/r3/unicode-lowercase');
if(existsSync(resolve(out,'source-data.json')))throw Error('Refusing to overwrite predecessor Unicode data');
if(process.versions.bun!=='1.4.3'||process.versions.unicode!=='17.0')throw Error('Expected retained Bun1.4.3 / Unicode17.0');
const units=(s:string)=>Array.from({length:s.length},(_,i)=>s.charCodeAt(i));
const mappings:Array<[number,number[]]>=[];
const cased:Array<[number,number]>=[],ignorable:Array<[number,number]>=[];
const append=(ranges:Array<[number,number]>,cp:number)=>{const last=ranges.at(-1);if(last&&last[1]+1===cp)last[1]=cp;else ranges.push([cp,cp]);};
const casedPattern=/^\p{Cased}$/u,ignorablePattern=/^\p{Case_Ignorable}$/u;
for(let cp=0;cp<=0x10ffff;cp++){
 const text=String.fromCodePoint(cp),lower=text.toLowerCase();
 if(text!==lower)mappings.push([cp,units(lower)]);
 if(casedPattern.test(text))append(cased,cp);
 if(ignorablePattern.test(text))append(ignorable,cp);
}
const samples=['','ΟΣ','ΟΣΑ','ΟΣ\u0301','ΟΣ.\u0301Α',"ΟΣ'Α",'Σ','AΣ','AΣ\u200dB','AΣ\u200d','AΣ\ud800','A\ud800Σ','İIıi','I\u0307','AΣ\u{16ea0}','\u{10400}Σ','ΟΣ.Α','ΟΣ-Α','ΟΣ_Α'];
// Context probes exercise every property interval boundary independently of Rust's tables.
for(const ranges of [cased,ignorable])for(const [start,end]of ranges)for(const cp of new Set([start,end])){
 const text=String.fromCodePoint(cp);samples.push(text+'Σ','AΣ'+text,'AΣ'+text+'B');
}
const contexts=samples.map(text=>({input:units(text),expected:units(text.toLowerCase())}));
const source={scope:'Pinned default String.toLowerCase scalar mappings and Final_Sigma properties; not locale-specific casing',runtime:process.versions,mappings,cased,caseIgnorable:ignorable,contexts};
mkdirSync(out,{recursive:true});
const raw=JSON.stringify(source)+'\n';writeFileSync(resolve(out,'source-data.json'),raw);
const lines=['// SPDX-License-Identifier: MIT OR Apache-2.0','// Generated by scripts/rust-migration/r3/capture-lowercase.ts from Bun1.4.3 Unicode17.0.','// Inert language-kernel data; do not edit.','const LOWERCASE_MAPPINGS: &[(u32, &[u16])] = &[',...mappings.map(([cp,result])=>`    (${cp}, &[${result.join(', ')}]),`),'];','const CASED_RANGES: &[(u32, u32)] = &[',...cased.map(([a,b])=>`    (${a}, ${b}),`),'];','const CASE_IGNORABLE_RANGES: &[(u32, u32)] = &[',...ignorable.map(([a,b])=>`    (${a}, ${b}),`),'];',''];
const target=resolve(root,'crates/umf-codegen/src/access/unicode_lowercase_data.rs');writeFileSync(target,lines.join('\n'));
const sha=(bytes:string|Uint8Array)=>createHash('sha256').update(bytes).digest('hex');
writeFileSync(resolve(out,'receipt.json'),JSON.stringify({sourceSha256:sha(raw),captureSha256:sha(readFileSync(import.meta.filename)),rustDataSha256:sha(readFileSync(target)),scalarDomain:0x110000,changedMappings:mappings.length,casedRanges:cased.length,caseIgnorableRanges:ignorable.length,contextControls:contexts.length,runtime:process.versions},null,2)+'\n');
console.log(JSON.stringify({changedMappings:mappings.length,casedRanges:cased.length,caseIgnorableRanges:ignorable.length,contextControls:contexts.length}));
