import assert from 'node:assert/strict';
import {assertControlParity,assertRuntimeParity,browserMime,isSameOriginRequest,browserLaunchOptions,browserBudgetMs} from './support.mjs';
const runtime={status:'pass',cases:[{id:'x',outcome:{ok:true},defaultElapsedMs:3,defaultOwnShapeSha256:'a'}]};
assert.doesNotThrow(()=>assertRuntimeParity(runtime,{...runtime,cases:[{...runtime.cases[0],defaultElapsedMs:900}]}));
assert.throws(()=>assertRuntimeParity(runtime,{...runtime,cases:[{...runtime.cases[0],outcome:{ok:false}}]}),/semantic\/shape/);
const result={ok:false,error:{code:'CORE_KIND_RECEIPT',path:''}};
assert.doesNotThrow(()=>assertControlParity('receipt',result,result,[],[],'CORE_KIND_RECEIPT','',[]));
assert.throws(()=>assertControlParity('receipt',result,result,['current'],[],'CORE_KIND_RECEIPT','',[]),/error\/order/);
assert.throws(()=>assertControlParity('receipt',result,result,[],[],'CORE_KIND_RECEIPT','/wrong',[]),/error\/order/);
assert.deepEqual(browserLaunchOptions,{headless:true});
assert.equal(browserBudgetMs,600_000);
assert.equal(browserMime('/'),'text/html; charset=utf-8');
assert.equal(browserMime('/pkg/dist/umf_core_wasm_bg.wasm'),'application/wasm');
assert.equal(browserMime('/suite.mjs'),'application/javascript; charset=utf-8');
assert.equal(isSameOriginRequest('http://127.0.0.1:123/pkg/a.js','http://127.0.0.1:123'),true);
assert.equal(isSameOriginRequest('https://example.test/a.js','http://127.0.0.1:123'),false);
process.stdout.write('installed runner controls pass\n');
