"""Emit the closed 76-edge x 2-phase typed join-refinement corpus.

The transition table is the reviewed SQL null-extension oracle, separate from
runtime ancestor walking and the typing overload generator.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATES = (
    ('one_required', '.join(Order.c.peer.to_alias(one))', 1, ((0, 2), (0, 2))),
    ('one_optional', '.join(Order.c.parent.to_alias(one))', 1, ((1, 3), (0, 3))),
    ('two_required', '.join(Order.c.peer.to_alias(one)).join(Order.c.peer.to_alias(two))', 2, ((0, 4), (0, 4), (0, 4))),
    ('first_optional', '.join(Order.c.parent.to_alias(one)).join(Order.c.peer.to_alias(two))', 2, ((1, 5), (0, 5), (1, 5))),
    ('second_optional', '.join(Order.c.peer.to_alias(one)).join(Order.c.parent.to_alias(two))', 2, ((2, 6), (2, 6), (0, 6))),
    ('optional_siblings', '.join(Order.c.parent.to_alias(one)).join(Order.c.optional_peer.to_alias(two))', 2, ((3, 7), (2, 7), (1, 7))),
    ('optional_chain', '.join(Order.c.parent.to_alias(one)).join(one.c.parent.to_alias(two))', 2, ((3, 7), (2, 7), (0, 7))),
)
FORMS = (('required_default', 'peer', '', 0), ('required_left', 'peer', ', how="left"', 1), ('optional_default', 'parent', '', 1), ('optional_inner', 'parent', ', how="inner"', 0))


def emit(root: Path) -> None:
    lines = ['"""Generated by scripts/generate-access-refinement-cases.py; no ignores."""',
             'from refinement_shop import Order', 'from umf_access.dsl import Terminal, count, query',
             'class One: pass', 'class Two: pass', 'class Three: pass',
             'one,two,three=Order.alias(One),Order.alias(Two),Order.alias(Three)', '']
    cases = []
    owners = ('Order', 'one', 'two', 'three')
    for state, prefix, prior, transitions in STATES:
        for source in range(prior+1):
            for form, relation, how, kind in FORMS:
                mask = transitions[source][kind]
                for grouped in (False, True):
                    name = f'{state}_s{source}_{form}_{"grouped" if grouped else "rows"}'
                    query = 'Order.objects' + prefix
                    if grouped:
                        query += '.group_by(' + ','.join(o+'.c.order_id' for o in owners[:prior+1]) + ')'
                    query += f'.join({owners[source]}.c.{relation}.to_alias({owners[prior+1]}){how})'
                    selected = list(owners[:prior+1 if grouped else prior+2])
                    carriers = ['str' + (' | None' if i and mask & (1 << (i-1)) else '') for i in range(len(selected))]
                    columns = [o+'.c.order_id' for o in selected]
                    if grouped:
                        carriers.append('int'); columns.append('count()')
                    query += '.select(' + ','.join(columns) + ').limit(3).all()'
                    lines += ['@query', f'def {name}() -> Terminal[list[tuple[{", ".join(carriers)}]]]:', '    return '+query, '']
                    cases.append({'name':name,'priorEdges':prior,'sourceIndex':source,'form':form,'grouped':grouped,'nullableMask':mask,'ownerCount':prior+2})
    target = root/'tests/compilation/python/static/joins/refinement_matrix.py'
    target.write_text('\n'.join(lines))
    target.with_suffix('.json').write_text(json.dumps({'version':'umf-join-refinement-matrix/0.1','states':7,'edgeTransitions':76,'phases':2,'cases':cases},indent=2)+'\n')


if __name__ == '__main__':
    emit(ROOT)
