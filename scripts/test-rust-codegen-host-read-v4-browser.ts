import {mkdtemp,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {chromium} from 'playwright';
import {generatePythonClient} from '../src/access';

const temp=await mkdtemp(join(tmpdir(),'umf-host-read-v4-browser-'));
const candidate=Bun.file(process.env.UMF_V4_BUNDLE_PATH??join(process.cwd(),'dist/umf-rust-codegen-candidate-v4-browser.js'));
const wasm=Bun.file(process.env.UMF_WASM_PATH??join(process.cwd(),'dist/umf_core_wasm_bg.wasm'));
const commerce=await Bun.file('tests/unified/commerce.json').text();
const parityRequest={text:commerce,package:'shop',records:[{module:'commerce',element:'Order'}],actions:[{module:'commerce',action:'shipOrder'}]};
const expected=generatePythonClient(parityRequest as any);
const server=Bun.serve({hostname:'127.0.0.1',port:0,async fetch(request){
 const path=new URL(request.url).pathname;
 if(path==='/candidate.js')return new Response(candidate,{headers:{'content-type':'text/javascript'}});
 if(path==='/umf_core_wasm_bg.wasm')return new Response(wasm,{headers:{'content-type':'application/wasm'}});
 if(path==='/commerce.json')return new Response(commerce,{headers:{'content-type':'application/json'}});
 if(path==='/expected.json')return Response.json(expected);
 return new Response('<!doctype html><title>V4 browser test</title>');
}});
let browser:Awaited<ReturnType<typeof chromium.launch>>|undefined;
try{
 browser=await chromium.launch({headless:true,...(process.env.UMF_CHROMIUM_PATH?{executablePath:process.env.UMF_CHROMIUM_PATH}:{})});
 const page=await browser.newPage();let externalRequests=0;
 page.on('request',request=>{if(!request.url().startsWith(server.url.origin))externalRequests++;});
 await page.goto(server.url.href);
 const outcome=await page.evaluate(async()=>{
  const api=await import(new URL('/candidate.js',location.href).href) as any;
  const text=await(await fetch('/commerce.json')).text();
  const expected=await(await fetch('/expected.json')).json();
  const generate=await api.createPythonClientRustCandidateV4();
  const output=generate({text,package:'shop',records:[{module:'commerce',element:'Order'}],actions:[{module:'commerce',action:'shipOrder'}]});
  const canonical=(value:any)=>JSON.stringify(value,(key,item)=>item&&typeof item==='object'&&!Array.isArray(item)?Object.fromEntries(Object.keys(item).sort().map(name=>[name,item[name]])):item);
  if(canonical(output)!==canonical(expected))throw new Error('browser V4 generated bytes differ from TypeScript');
  let falsySelectionsRejected=0;
  for(const key of ['records','actions'])for(const value of [false,0,'']){
   let invalid:any;try{generate({text,package:'shop',[key]:value});}catch(error){invalid=error;}
   if(!(invalid instanceof TypeError)||invalid.message!=='Selection must be an array')throw new Error(`browser V4 accepted non-null falsy ${key}`);
   falsySelectionsRejected++;
  }
  let indexed=0,caught:any;
  const records=new Proxy(new Array(10_001),{get(target,key,receiver){if(typeof key==='string'&&/^\d+$/.test(key))indexed++;return Reflect.get(target,key,receiver);}});
  try{generate({text,package:'shop',records});}catch(error){caught=error;}
  if(indexed!==0||caught?.code!=='RESOURCE_LIMIT'||caught?.path!=='/records')throw new Error('browser V4 raw-position refusal mismatch');
  const selected:any[]=[{module:'commerce',element:'Customer'},{module:'commerce',element:'Order'}];let listRead=false,mutated=false;
  const controlled=await api.createPythonClientRustCandidateV4({controls:{meter(){if(listRead&&!mutated){mutated=true;selected[1]={module:'commerce',element:'Missing'};}}}});
  let meterError:any;try{controlled({text,package:'shop',get records(){listRead=true;return selected;}});}catch(error){meterError=error;}
  if(!mutated||meterError?.path!=='commerce.Missing'||meterError?.message!=='Selected Record not found')throw new Error('browser V4 inter-item meter mutation mismatch');
  const live=globalThis.Uint16Array;let poisoned:any;
  try{poisoned=generate({get text(){globalThis.Uint16Array=(()=>{throw new Error('live Uint16Array accessed');}) as any;return text;},package:'shop'});}finally{globalThis.Uint16Array=live;}
  if(!poisoned.files.length)throw new Error('browser V4 frame intrinsic poisoning mismatch');
  return {profile:api.PYTHON_CLIENT_HOST_READ_V4_PROFILE,rawCode:caught.code,selectedMutation:meterError.path,files:poisoned.files.length,exactGeneratedFiles:output.files.length,falsySelectionsRejected,browser:navigator.userAgent};
 });
 if(externalRequests!==0)throw new Error(`browser V4 made ${externalRequests} external requests`);
 console.log(JSON.stringify({...outcome,externalRequests}));
}finally{await browser?.close();server.stop(true);await rm(temp,{recursive:true,force:true});}
