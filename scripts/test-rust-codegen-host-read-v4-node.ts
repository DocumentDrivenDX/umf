import {expect,test} from 'bun:test';
import {generatePythonClient} from '../src/access';
import {createPythonClientRustCandidateV4} from '../src/node-v4';

const source=await Bun.file(new URL('../tests/unified/commerce.json',import.meta.url)).text();

test('V4 Node candidate refuses over-limit raw positions before indexed reads',async()=>{
 const generator=await createPythonClientRustCandidateV4();
 let indexed=0;
 const records=new Proxy(new Array(10_001),{get(target,key,receiver){if(typeof key==='string'&&/^\d+$/.test(key))indexed++;return Reflect.get(target,key,receiver);}});
 let caught:any;try{generator({text:source,package:'shop',records} as any);}catch(error){caught=error;}
 expect(indexed).toBe(0);
 expect(caught).toMatchObject({code:'RESOURCE_LIMIT',path:'/records',message:'V4 host-read resource limit exceeded'});
},30_000);

test('V4 Node candidate rejects non-null falsy records and actions as arrays',async()=>{
 const generator=await createPythonClientRustCandidateV4();
 for(const key of ['records','actions'] as const){
  for(const value of [false,0,'']){
   let caught:any;try{generator({text:source,package:'shop',[key]:value} as any);}catch(error){caught=error;}
   expect(caught).toBeInstanceOf(TypeError);
   expect(caught.message).toBe('Selection must be an array');
  }
 }
},120_000);

test('V4 Node candidate checks cumulative duplicate identity text before deduplication',async()=>{
 const generator=await createPythonClientRustCandidateV4();
 const records=Array.from({length:5},()=>({module:'x'.repeat(1_000_000),element:''}));
 let caught:any;try{generator({text:source,package:'shop',records} as any);}catch(error){caught=error;}
 expect(caught).toMatchObject({code:'RESOURCE_LIMIT',path:'/records',message:'V4 host-read resource limit exceeded'});
},30_000);

test('V4 Node candidate exposes the meter window between captured indexed reads',async()=>{
 const document=JSON.parse(source);
 const records:any[]=[{module:'commerce',element:'Customer'},{module:'commerce',element:'Order'}];
 let listRead=false,mutated=false;
 const generator=await createPythonClientRustCandidateV4({controls:{meter(){if(listRead&&!mutated){mutated=true;records[1]={module:'commerce',element:'Missing'};}}}});
 let caught:any;
 try{generator({text:JSON.stringify(document),package:'shop',get records(){listRead=true;return records;}} as any);}catch(error){caught=error;}
 expect(mutated).toBe(true);
 expect(caught).toMatchObject({code:'ACCESS_UNSUPPORTED',path:'commerce.Missing',message:'Selected Record not found'});
},30_000);

test('V4 Node host-read profile remains explicit and does not alter ordinary source selection',async()=>{
 const generator=await createPythonClientRustCandidateV4();
 const output=generator({text:source,package:'shop',records:[{module:'commerce',element:'Customer'}]} as any);
 expect(output.files.length).toBeGreaterThan(0);
},30_000);

test('V4 Node output preserves exact TypeScript-generated bytes for selected records and actions',async()=>{
 const request={text:source,package:'shop',records:[{module:'commerce',element:'Order'}],actions:[{module:'commerce',action:'shipOrder'}]};
 const expected=generatePythonClient(request as any);
 const actual=await createPythonClientRustCandidateV4();
 expect(actual(request as any)).toEqual(expected);
},30_000);

test('V4 Node candidate preserves the legacy unpaired-surrogate INPUT error shape',async()=>{
 const generator=await createPythonClientRustCandidateV4();
 let reads=0,caught:unknown;
 try{generator({get text(){reads++;return reads<=2?source:'\ud800';},package:'shop'} as any);}catch(error){caught=error;}
 expect(reads).toBe(3);
 expect(caught).toBeInstanceOf(Error);
 expect((caught as Error).constructor.name).toBe('Error');
 expect((caught as Error).message).toBe('INPUT');
},30_000);

test('V4 Node candidate preserves the legacy source-text LIMIT error shape',async()=>{
 const generator=await createPythonClientRustCandidateV4();
 let caught:any;try{generator({text:'x'.repeat(4_000_001),package:'shop'} as any);}catch(error){caught=error;}
 expect(caught).toMatchObject({code:'LIMIT',message:'Source text exceeds limit',path:''});
},30_000);
