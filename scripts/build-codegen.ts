/** Development-only packaging boundary. Installed Python never invokes this script. */
import {mkdir,readdir,readFile,writeFile,rm} from 'node:fs/promises';
import {dirname,join,relative,resolve,basename} from 'node:path';
import {createHash} from 'node:crypto';
import {deterministicGzip} from './codegen/gzip';
const compare=(a:string,b:string)=>a<b?-1:a>b?1:0;
const root=resolve(import.meta.dir,'..');
const output=join(root,'python/umf_codegen/src/umf_codegen');
const result=await Bun.build({entrypoints:[join(root,'scripts/codegen/entry.ts')],target:'browser',format:'iife',
 minify:true,metafile:true,banner:'// SPDX-License-Identifier: MIT OR Apache-2.0\n// Bundled dependencies retain their individual licenses in notices/.',
 naming:'generator.js'});
if(!result.success||!result.metafile)throw Error(result.logs.join('\n'));
if(Object.values(result.metafile.outputs).some(item=>item.imports.length))throw Error('Installed codegen must be one self-contained bundle');
const hash=(bytes:Uint8Array|string)=>createHash('sha256').update(bytes).digest('hex');
const payloads=new Map<string,Uint8Array>();
const js=await result.outputs[0]!.text();
payloads.set('generator.js.gz',deterministicGzip(new TextEncoder().encode(js)));
const inputs:Record<string,string>={},dependencies=new Map<string,{name:string;version:string;license:string;files:string[]}>();
for(const [name] of Object.entries(result.metafile.inputs).sort(([a],[b])=>compare(a,b))){
 const full=resolve(root,name),portable=relative(root,full).replaceAll('\\','/');
 if(portable.startsWith('../'))throw Error('Codegen input outside repository: '+name);
 inputs[portable]=hash(await readFile(full));
 if(!portable.startsWith('node_modules/'))continue;
 let directory=dirname(full);
 while(directory!==root){
  try{const raw=await readFile(join(directory,'package.json'));const metadata=JSON.parse(raw.toString());
   if(metadata.name===undefined&&metadata.version===undefined){directory=dirname(directory);continue;}
   if(typeof metadata.name!=='string'||typeof metadata.version!=='string'||typeof metadata.license!=='string')throw Error('Unlicensed codegen dependency: '+directory);
   if(!dependencies.has(metadata.name)){
    const prefix='notices/'+metadata.name.replaceAll('/','__')+'/';
    const files=(await readdir(directory)).filter(n=>/^(licen[cs]e|copying|notice)([._-]|$)/i.test(n)).sort();
    if(!files.length)throw Error('Missing third-party license text: '+metadata.name);
    payloads.set(prefix+'package.json',new Uint8Array(raw));
    for(const file of files)payloads.set(prefix+file,new Uint8Array(await readFile(join(directory,file))));
    dependencies.set(metadata.name,{name:metadata.name,version:metadata.version,license:metadata.license,files:files.map(n=>prefix+n)});
   }
   break;
  }catch(error){if((error as NodeJS.ErrnoException).code!=='ENOENT')throw error;}
  directory=dirname(directory);
 }
 if(directory===root)throw Error('Cannot identify codegen dependency '+basename(full));
}
inputs['scripts/build-codegen.ts']=hash(await readFile(join(root,'scripts/build-codegen.ts')));
inputs['scripts/codegen/gzip.ts']=hash(await readFile(join(root,'scripts/codegen/gzip.ts')));
const manifest={profile:'umf.codegen-v8/1',generator:'generatePythonClient',engine:'mini-racer==0.14.1',
 operations:['generatePythonClient','compileTableDeployment','verifyTableDeployment'],
 v8:'14.4.258.23',bundleSha256:hash(js),builder:'bun@'+Bun.version,license:'MIT OR Apache-2.0',inputs,
 dependencies:[...dependencies.values()].sort((a,b)=>compare(a.name,b.name)),
 files:Object.fromEntries([...payloads].sort(([a],[b])=>compare(a,b)).map(([name,bytes])=>[name,hash(bytes)]))};
const manifestBytes=JSON.stringify(manifest,null,2)+'\n';payloads.set('manifest.json',new TextEncoder().encode(manifestBytes));
payloads.set('../_release.py',new TextEncoder().encode('# SPDX-License-Identifier: MIT OR Apache-2.0\n# Generated by scripts/build-codegen.ts\nMANIFEST_SHA256 = '+JSON.stringify(hash(manifestBytes))+'\n'));
const assets=join(output,'_assets');
if(process.argv.includes('--check')){
 for(const [name,bytes] of payloads){const path=name.startsWith('../')?join(output,name.slice(3)):join(assets,name);if(!Buffer.from(await readFile(path)).equals(Buffer.from(bytes)))throw Error('Stale codegen payload: '+name+'; expected='+hash(await readFile(path))+' observed='+hash(bytes)+' bundle='+hash(js));}
 console.log(JSON.stringify({status:'current',inputs:Object.keys(inputs).length,files:payloads.size}));
}else{
 await rm(assets,{recursive:true,force:true});await mkdir(assets,{recursive:true});
 for(const [name,bytes] of payloads){const path=name.startsWith('../')?join(output,name.slice(3)):join(assets,name);await mkdir(dirname(path),{recursive:true});await writeFile(path,bytes);}
 console.log(JSON.stringify({status:'built',inputs:Object.keys(inputs).length,files:payloads.size,bytes:js.length}));
}
