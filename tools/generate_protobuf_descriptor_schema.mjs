// Generate the Rust descriptor schema table from the pinned Buf descriptor
// metadata. The upstream descriptor.proto hash is emitted into the table so
// reviewers can trace the generated wire schema to its vendored source.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { file_google_protobuf_descriptor as file } from '../node_modules/@bufbuild/protobuf/dist/esm/wkt/gen/google/protobuf/descriptor_pb.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(resolve(root, 'fixtures/protobuf/upstream/google/protobuf/descriptor.proto'));
const sourceHash = createHash('sha256').update(source).digest('hex');
const upstreamManifest = JSON.parse(await readFile(resolve(root, 'fixtures/protobuf/upstream/manifest.json'), 'utf8'));
if (upstreamManifest.sha256['google/protobuf/descriptor.proto'] !== sourceHash) throw new Error('vendored descriptor.proto differs from pinned upstream manifest');
const receipt = JSON.parse(await readFile(resolve(root, 'docs/helix/04-build/evidence/rust-migration/r5-protobuf-descriptor-codec/predecessor.json'), 'utf8'));
const packageJson = JSON.parse(await readFile(resolve(root, 'node_modules/@bufbuild/protobuf/package.json'), 'utf8'));
if (packageJson.version !== receipt.runtime.bufbuildProtobuf) throw new Error(`expected @bufbuild/protobuf ${receipt.runtime.bufbuildProtobuf}, got ${packageJson.version}`);
for (const [relative, expected] of Object.entries(receipt.bufPackageClosure)) {
  const actual = createHash('sha256').update(await readFile(resolve(root, 'node_modules/@bufbuild/protobuf', relative))).digest('hex');
  if (actual !== expected) throw new Error(`Buf package file differs from frozen receipt: ${relative}`);
}
const closureHash = createHash('sha256').update(JSON.stringify(receipt.bufPackageClosure)).digest('hex');
if (closureHash !== receipt.runtime.bufPackageClosureSha256) throw new Error('frozen Buf closure receipt is inconsistent');
const ident = value => value.replaceAll(/[^A-Za-z0-9_]/g, '_');
const q = value => JSON.stringify(value);
const scalarName = {
  1: 'Double', 2: 'Float', 3: 'Int64', 4: 'UInt64', 5: 'Int32', 6: 'Fixed64',
  7: 'Fixed32', 8: 'Bool', 9: 'String', 10: 'Group', 11: 'Message', 12: 'Bytes',
  13: 'UInt32', 14: 'Enum', 15: 'SFixed32', 16: 'SFixed64', 17: 'SInt32', 18: 'SInt64',
};
const messages = [...file.messages].flatMap(function flatten(message) {
  return [message, ...message.nestedMessages.flatMap(flatten)];
});
if (messages.length !== 34) throw new Error(`expected 34 Buf 2.15 descriptor messages, got ${messages.length}`);
const enums = [...file.enums, ...messages.flatMap(message => message.nestedEnums)];
const allTypes = new Set([...messages.map(m => m.typeName), ...enums.map(e => e.typeName)]);
for (const message of messages) for (const field of message.fields) {
  if (field.message && !allTypes.has(field.message.typeName)) throw new Error(`missing message ${field.message.typeName}`);
  if (field.enum && !allTypes.has(field.enum.typeName)) throw new Error(`missing enum ${field.enum.typeName}`);
}
const rust = `// Generated by tools/generate_protobuf_descriptor_schema.mjs; do not edit.\n// Source: fixtures/protobuf/upstream/google/protobuf/descriptor.proto\n// SHA-256: ${sourceHash}\n\n` +
`// Buf receipt: docs/helix/04-build/evidence/rust-migration/r5-protobuf-descriptor-codec/predecessor.json\n// Buf 2.15 closure SHA-256: ${closureHash}\n` +
`pub(super) const DESCRIPTOR_PROTO_SHA256: &str = ${q(sourceHash)};\npub(super) const BUF_PACKAGE_CLOSURE_SHA256: &str = ${q(closureHash)};\n` +
`pub(super) static MESSAGES: &[MessageSpec] = &[\n` + messages.map(message => {
  const fields = message.fields.map(field => {
    const kind = field.fieldKind === 'list' ? `FieldKind::Repeated(${field.listKind === 'message' ? `WireKind::Message(${q(field.message.typeName)})` : field.listKind === 'enum' ? `WireKind::Enum(${q(field.enum.typeName)})` : `WireKind::${scalarName[field.scalar]}`})`
      : field.fieldKind === 'message' ? `FieldKind::Singular(WireKind::Message(${q(field.message.typeName)}))`
      : field.fieldKind === 'enum' ? `FieldKind::Singular(WireKind::Enum(${q(field.enum.typeName)}))`
      : `FieldKind::Singular(WireKind::${scalarName[field.scalar]})`;
    const hasOneof = Object.hasOwn(field.proto, 'oneofIndex');
    const oneof = hasOneof ? `Some(${field.proto.oneofIndex})` : 'None';
    const defaultValue = field.proto.defaultValue === undefined ? 'None' : `Some(${q(String(field.proto.defaultValue))})`;
    return `        FieldSpec { name: ${q(field.name)}, number: ${field.number}, kind: ${kind}, presence: ${field.presence}, default_value: ${defaultValue}, packed: ${Boolean(field.packed)}, oneof: ${oneof} },`;
  }).join('\n');
  return `    MessageSpec { name: ${q(message.typeName)}, fields: &[\n${fields}\n    ] },`;
}).join('\n') + `\n];\n\npub(super) static ENUMS: &[EnumSpec] = &[\n` + enums.map(en =>
  `    EnumSpec { name: ${q(en.typeName)}, open: ${Boolean(en.open)}, values: &[${en.values.map(v => v.number).join(', ')}] },`
).join('\n') + `\n];\n`;
const destination = resolve(root, 'crates/umf-core/src/protobuf_descriptor_schema.rs');
if (process.argv.includes('--check')) {
  const existing = await readFile(destination, 'utf8').catch(() => '');
  if (existing !== rust) throw new Error(`${destination} is stale`);
} else if (process.argv.includes('--stdout')) process.stdout.write(rust);
else await writeFile(destination, rust);
console.log(`messages=${messages.length} enums=${enums.length} descriptor.proto sha256=${sourceHash}`);
