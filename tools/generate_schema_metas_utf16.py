#!/usr/bin/env python3
"""Encode literal UTF-8 source as Rust u16 data; never parse/validate JSON.

Defaults bind the existing schema_metas.json source and its generated sibling.
Explicit paths support independent encoding controls without changing defaults.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/umf-core/src/schema_metas.json"
OUTPUT = ROOT / "crates/umf-core/src/schema_metas_utf16.rs"


def source_units(raw: bytes) -> tuple[int, ...]:
    # Strict UTF-8 preserves U+FEFF and all newline/escape/trailing characters.
    # No utf-8-sig, text-mode newline translation, strip, or JSON interpretation.
    encoded = raw.decode("utf-8").encode("utf-16-le")
    return tuple(encoded[i] | (encoded[i + 1] << 8)
                 for i in range(0, len(encoded), 2))


def render(raw: bytes) -> bytes:
    units = source_units(raw)
    lines = [
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "// @generated by tools/generate_schema_metas_utf16.py; do not edit.",
        "// Encoding only. This data establishes no JSON/schema acceptance.",
        f"// Original UTF-8 bytes: {len(raw)}; UTF-16 units: {len(units)}.",
        f"// Source SHA-256 (custody only): {sha256(raw).hexdigest()}",
        "#[rustfmt::skip]",
        "pub(super) static SCHEMA_METAS_UTF16: &[u16] = &[",
    ]
    for start in range(0, len(units), 16):
        lines.append("    " + " ".join(f"0x{unit:04x}," for unit in units[start:start + 16]))
    lines.append("];")
    return ("\n".join(lines) + "\n").encode("ascii")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true",
                        help="Refuse missing/stale output; write nothing.")
    args = parser.parse_args(argv)
    try:
        expected = render(args.source.read_bytes())
        if args.check:
            try:
                actual = args.output.read_bytes()
            except FileNotFoundError:
                print(f"missing encoded source: {args.output}", file=sys.stderr)
                return 1
            # Exact rendering equality covers EVERY typed unit and original-byte
            # custody header. A hash-only comparison cannot admit stale units.
            if actual != expected:
                print(f"stale encoded source: {args.output}", file=sys.stderr)
                return 1
            print(f"verified exact UTF-16 source: {args.output}")
        else:
            args.output.write_bytes(expected)
            print(f"generated typed UTF-16 source: {args.output}")
    except (OSError, UnicodeError) as exc:
        print(f"source encoding refused: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
