#!/usr/bin/env python3
"""Encode two original operation JSON sources as literal UTF-16 units only.

This recipe does not parse JSON or establish schema/profile acceptance. Runtime
text admission, parsing, compilation and semantic checks remain required.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OPERATION_SOURCE = ROOT / "spec/extensions/tables/operation.schema.json"
ROW_EXPRESSION_SOURCE = ROOT / "spec/extensions/tables/operation-0.2.schema.json"
OUTPUT = ROOT / "crates/umf-codegen/src/operation_schemas_utf16.rs"


def source_units(raw: bytes) -> tuple[int, ...]:
    # Strict UTF-8; preserve BOM, CRLF, whitespace, escapes and trailing content.
    # Explicit LE encoding defines integers; no runtime endian reinterpretation.
    encoded = raw.decode("utf-8", "strict").encode("utf-16-le")
    return tuple(encoded[i] | (encoded[i + 1] << 8)
                 for i in range(0, len(encoded), 2))


def render(operation_raw: bytes, row_expression_raw: bytes) -> bytes:
    lines = [
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "// @generated by tools/generate_operation_schema_utf16.py; do not edit.",
        "// Encoding only. No JSON/schema acceptance or descriptor is generated.",
    ]
    for path, symbol, raw in (
        ("spec/extensions/tables/operation.schema.json", "OPERATION_SCHEMA_UTF16", operation_raw),
        ("spec/extensions/tables/operation-0.2.schema.json", "ROW_EXPRESSION_OPERATION_SCHEMA_UTF16", row_expression_raw),
    ):
        units = source_units(raw)
        lines.extend([
            f"// Original source: {path}",
            f"// Original UTF-8 bytes: {len(raw)}; UTF-16 units: {len(units)}.",
            f"// Source SHA-256 (custody only): {sha256(raw).hexdigest()}",
            "#[rustfmt::skip]",
            f"pub(super) static {symbol}: &[u16] = &[",
        ])
        for start in range(0, len(units), 16):
            lines.append("    " + " ".join(f"0x{unit:04x}," for unit in units[start:start + 16]))
        lines.append("];")
    return ("\n".join(lines) + "\n").encode("ascii")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--operation-source", type=Path, default=OPERATION_SOURCE)
    parser.add_argument("--row-expression-source", type=Path, default=ROW_EXPRESSION_SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true",
                        help="Refuse missing/stale output; write nothing.")
    args = parser.parse_args(argv)
    try:
        expected = render(args.operation_source.read_bytes(),
                          args.row_expression_source.read_bytes())
        if args.check:
            try:
                actual = args.output.read_bytes()
            except FileNotFoundError:
                print(f"missing encoded operation sources: {args.output}", file=sys.stderr)
                return 1
            if actual != expected:
                print(f"stale encoded operation sources: {args.output}", file=sys.stderr)
                return 1
            print(f"verified exact UTF-16 operation sources: {args.output}")
        else:
            args.output.write_bytes(expected)
            print(f"generated typed UTF-16 operation sources: {args.output}")
    except (OSError, UnicodeError) as exc:
        print(f"operation source encoding refused: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
