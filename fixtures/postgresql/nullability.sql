CREATE SCHEMA availability;
CREATE DOMAIN availability.required_domain AS integer NOT NULL;
CREATE DOMAIN availability.default_domain AS integer DEFAULT 11;
CREATE TABLE availability.plain(value integer);
CREATE TABLE availability.required(value integer NOT NULL DEFAULT 7);
CREATE TABLE availability.domain_required(value availability.required_domain);
CREATE TABLE availability.domain_default(value availability.default_domain);
CREATE TABLE availability.column_default(value availability.default_domain DEFAULT 13);
CREATE TABLE availability.positive(value integer CHECK(value > 0));
CREATE TABLE availability.checked_required(value integer CHECK(value IS NOT NULL));
CREATE TABLE availability.unvalidated(value integer);
INSERT INTO availability.unvalidated VALUES(NULL);
ALTER TABLE availability.unvalidated ADD CONSTRAINT required_later CHECK(value IS NOT NULL) NOT VALID;
CREATE TABLE availability.identity_value(value integer GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE availability.generated_value(input integer, value integer GENERATED ALWAYS AS (coalesce(input,7)) STORED);
CREATE VIEW availability.outer_null AS SELECT r.value FROM (VALUES(1)) AS l(id) LEFT JOIN availability.required r ON false;
