CREATE SCHEMA facet;
CREATE TABLE facet.int16(value smallint);
CREATE TABLE facet.int32(value integer);
CREATE TABLE facet.int64(value bigint);
CREATE TABLE facet.signed8(value smallint CHECK (value BETWEEN -128 AND 127));
CREATE TABLE facet.unsigned8(value smallint CHECK (value BETWEEN 0 AND 255));
CREATE TABLE facet.decimal_pair(value numeric(5,2));
CREATE TABLE facet.decimal_bare(value numeric);
CREATE TABLE facet.decimal_negative_scale(value numeric(2,-3));
CREATE TABLE facet.decimal_over_scale(value numeric(3,5));
CREATE TABLE facet.decimal_finite(value numeric(5,2) CHECK (value BETWEEN -999.99 AND 999.99));
CREATE TABLE facet.decimal_exact(value numeric CHECK (value BETWEEN -999.99 AND 999.99 AND value = trunc(value,2)));
CREATE TABLE facet.varchar1(value varchar(1));
CREATE TABLE facet.varchar2(value varchar(2));
CREATE TABLE facet.char2(value char(2));
CREATE TABLE facet.char_bare(value char);
CREATE TABLE facet.bpchar_bare(value bpchar);
CREATE TABLE facet.text_bound(value text CHECK (char_length(value) <= 2));
CREATE TABLE facet.text_zero(value text CHECK (char_length(value) <= 0));
CREATE TABLE facet.binary_bound(value bytea CHECK (octet_length(value) <= 2));
CREATE TABLE facet.float32(value real);
CREATE TABLE facet.float64(value double precision);
CREATE DOMAIN facet.positive_decimal AS numeric(5,2) CHECK (VALUE > 0);
CREATE TABLE facet.domain_value(value facet.positive_decimal);
CREATE TABLE facet.array_value(value numeric(5,2)[]);
CREATE TABLE facet.unvalidated(value numeric(5,2));
INSERT INTO facet.unvalidated VALUES ('NaN');
ALTER TABLE facet.unvalidated ADD CONSTRAINT finite_value CHECK (value BETWEEN -999.99 AND 999.99) NOT VALID;
COMMENT ON COLUMN facet.decimal_pair.value IS 'Declared precision/scale does not establish exact input conversion or exclude NaN';
CREATE TABLE facet.decimal_max_scale(value numeric(1000,1000));
CREATE TABLE facet.decimal_min_scale(value numeric(1000,-1000));
CREATE TABLE facet.varchar_max(value varchar(10485760));
CREATE TABLE facet.decimal_precision_only(value numeric(5));
