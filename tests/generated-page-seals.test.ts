import {test,expect} from 'bun:test';
import {createHash} from 'node:crypto';
import {buildKey,checkGeneratedClaim,checkCuratedClaim,checkInventory} from '../scripts/generated-page-seals';

test('generated output requires a distinct registered build key',()=>{
 const keys={keys:[{key_id:'build',role:'build'}]},config={issuer:{key_id:'human'},keys:{build:{key_id:'build'}}};
 expect(buildKey(config,keys)).toBe('build');
 for(const invalid of [{issuer:{key_id:'build'},keys:config.keys},{issuer:config.issuer},{...config,keys:{build:{key_id:'unknown'}}}])expect(()=>buildKey(invalid,keys)).toThrow();
 expect(()=>buildKey(config,{keys:[{key_id:'build',role:'human'}]})).toThrow();
});
test('generated inventory refuses missing, extra, duplicate and curated pages',()=>{
 const generated=['docs/helix/05-deploy/microsite/dist/reference/index.html'];
 expect(()=>checkInventory(generated,generated)).not.toThrow();
 for(const declared of [[],[...generated,...generated],[...generated,'docs/helix/05-deploy/microsite/dist/index.html'],[...generated,'docs/helix/05-deploy/microsite/dist/reference/../index.html']])expect(()=>checkInventory(declared,generated)).toThrow();
 expect(()=>checkInventory(generated,[...generated,'docs/helix/05-deploy/microsite/dist/reference/core.html'])).toThrow();
});
test('valid digest cannot hide a human signer or mixed claim on generated bytes',()=>{
 const bytes=Buffer.from('generated HTML'),colophon={composition:'model-primary'},claim={payload:{issuer:{key_id:'build'},subjects:[{digest:{alg:'sha256',value:createHash('sha256').update(bytes).digest('hex')}}],colophon},signatures:[{key_id:'build'}]};
 expect(()=>checkGeneratedClaim(bytes,claim,'build',colophon)).not.toThrow();
 expect(()=>checkGeneratedClaim(Buffer.from('changed'),claim,'build',colophon)).toThrow();
 const human=structuredClone(claim);human.payload.issuer.key_id='human';human.signatures[0]!.key_id='human';expect(()=>checkGeneratedClaim(bytes,human,'build',colophon)).toThrow();
 const mixed=structuredClone(claim);mixed.payload.colophon.composition='mixed';expect(()=>checkGeneratedClaim(bytes,mixed,'build',colophon)).toThrow();
});
test('build signatures cannot stand in for manual signatures on curated content',()=>{
 const claim={payload:{issuer:{key_id:'human'},colophon:{composition:'mixed'}},signatures:[{key_id:'human'}]};
 expect(()=>checkCuratedClaim(claim,'human')).not.toThrow();
 const wrong=structuredClone(claim);wrong.payload.issuer.key_id='build';wrong.signatures[0]!.key_id='build';expect(()=>checkCuratedClaim(wrong,'human')).toThrow();
 const generated=structuredClone(claim);generated.payload.colophon.composition='model-primary';expect(()=>checkCuratedClaim(generated,'human')).toThrow();
});
