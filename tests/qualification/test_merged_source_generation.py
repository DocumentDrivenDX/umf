def embedded_controller():
    text = WORKFLOW.read_text()
    marker = 'cat > "$RUNNER_TEMP/merged_source_generation.py" <<\'PYTHON\'\n'
    start = text.index(marker) + len(marker)
    end = text.index("\n          PYTHON", start)
    code = "\n".join(line[10:] if line.startswith("          ") else line
                       for line in text[start:end].splitlines())
    namespace = {"__name__": "workflow_controller"}
    exec(compile(code, str(WORKFLOW), "exec"), namespace)
    return namespace


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def action_identity(producer: str) -> bytes:
    return ("// SPDX-License-Identifier: MIT OR Apache-2.0\n"
            "// Generated by scripts/actions-plan-identity.ts from original source/schema bytes.\n"
            f'export const actionPlanProducerBuild = "sha256:{producer}";\n'
            f'export const actionPlanModelSchemaDigest = "sha256:{"b" * 64}";\n').encode()


def make_workspace(root: pathlib.Path, ctl: dict, pin_matches: bool = True) -> None:
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    root.mkdir(parents=True, exist_ok=True)
    data = b"pre-generation-data"
    resource_manifest = b'{"files":{},"profile":"umf.codegen-resources/1"}\n'
    action_manifest = b'{"format":"umf.action-runtime-resources/1"}\n'
    default = {name: name.encode() for name in ctl["OUTPUTS"]}
    default[DATA] = data
    default[RESOURCE_MANIFEST] = resource_manifest
    default[ACTION_MANIFEST] = action_manifest
    release_pin = sha(resource_manifest) if pin_matches else "0" * 64
    action_pin = sha(action_manifest) if pin_matches else "0" * 64
    default[RELEASE] = ("# SPDX-License-Identifier: MIT OR Apache-2.0\n"
                        f'RESOURCE_MANIFEST_SHA256 = "{release_pin}"\n'
                        'UMF_CODEGEN_VERSION = "0.10.10"\n'
                        'CODEGEN_PROTOCOL_VERSION = "umf-codegen-r3-seven-ops-nine-resources/1"\n').encode()
    default[ACTION_RUNTIME] = ("# SPDX-License-Identifier: MIT OR Apache-2.0\n"
                               f'_MANIFEST_SHA256 = "{action_pin}"\n'
                               "def unchanged_runtime_behavior():\n    return True\n").encode()
    default["src/extensions/actions/plan-identity.ts"] = action_identity("a" * 64)
    old_data_sha = sha(data)
    manifest = {"profile": "umf.metamodel.outputs/1",
                "provenance": {"modelSha256": "1" * 64, "compilerSha256": "2" * 64},
                "sources": {DATA: old_data_sha, "unrelated.rs": "3" * 64},
                "workspaceInputs": {DATA: old_data_sha},
                "compilerInputs": {DATA: old_data_sha}, "outputs": {}}
    default["spec/metamodel/generated/manifest.json"] = (json.dumps(manifest, sort_keys=True) + "\n").encode()
    for name, content in default.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    (root / "source.ts").write_text("source baseline\n")
    helper = root / "tools/tests/test_codegen_resource_literals.py"
    helper.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / "tools/tests/test_codegen_resource_literals.py", helper)
    spec = embedded_controller()
    helper_spec = spec["importlib"].util.spec_from_file_location("literal_inputs", helper)
    module = spec["importlib"].util.module_from_spec(helper_spec)
    helper_spec.loader.exec_module(module)
    for _, rel in module.INPUTS:
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('{"fixture":true}\n')
    subprocess.run(["git", "add", "-A"], cwd=root, check=True)


def update_manifest_data(root: pathlib.Path, digest: str, unrelated: bool = False) -> None:
    path = root / "spec/metamodel/generated/manifest.json"
    manifest = json.loads(path.read_text())
    for key in ("sources", "workspaceInputs", "compilerInputs"):
        if DATA in manifest[key]:
            manifest[key][DATA] = digest
    if unrelated:
        manifest["sources"]["unrelated.rs"] = "4" * 64
    path.write_text(json.dumps(manifest, sort_keys=True) + "\n")


def make_oracle(ctl: dict, snapshot: dict) -> dict:
    spec = ctl["importlib"].util.spec_from_file_location(
        "literal_inputs", ROOT / "tools/tests/test_codegen_resource_literals.py")
    module = ctl["importlib"].util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {"profile": "umf.gen1.g0-raw9-oracle/1", "decoderSha256": "d" * 64,
            "data": snapshot["outputs"][DATA],
            "roots": [{"role": role, "path": path, "bytes": 12, "sha256": "e" * 64}
                      for role, path in module.INPUTS]}


