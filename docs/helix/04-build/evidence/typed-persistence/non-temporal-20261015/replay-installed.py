    records.append({'name':name,'command':list(map(str,command)),'cwd':str(cwd),'exitCode':result.returncode,'expectedExit':expected,'log':name+'.log'})
    print(name,result.returncode,flush=True)
    if result.returncode!=expected:
        raise RuntimeError(name+' failed; '+(result.stdout+result.stderr)[-1500:])
    return result.stdout+result.stderr
